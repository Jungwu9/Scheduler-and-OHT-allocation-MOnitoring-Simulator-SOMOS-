# MachineDecisionMaker — gantt loader + plan-order dispatch
# ══════════════════════════════════════════════════════════════════════

class MachineDecisionMaker:
    """
    Role 1 — before simulation start (run_scheduling):
        Load the planned_gantt.csv produced by gen_machine.py as a GanttSchedule.
        (Does not "generate" a schedule. Reads an already-built plan.)

    Role 2 — during simulation (choose_next_job):
        Among the lots that have arrived at the machine in_buffer, pick the one with
        the earliest planned_ready (= gantt planned end time, i.e. planned processing
        order) -> replays the gantt plan order. Because congestion may cause a lot
        other than the planned one to arrive first, take the min "among those arrived".
    """

    def __init__(self, jssp_cfg: JSSPConfig = None, algorithm=None):
        global ACTIVE_MACHINE_DECISION
        self.jssp_cfg = jssp_cfg or JSSPConfig()

        # input path (default if absent in config)
        self.planned_gantt_csv = getattr(
            self.jssp_cfg, "planned_gantt_csv", "gantt_final/planned_gantt.csv")
        self.step_info_path = getattr(
            self.jssp_cfg, "step_info_path", "ProcessStepInfo.txt")
        self.pt_scale = float(getattr(self.jssp_cfg, "pt_scale", 0.75))

        # GanttSchedule = the routing/timing source consumed by the simulation
        self.schedule: Optional[GanttSchedule] = None
        # backward-compat alias. (Main's .jssp_data references to be replaced with schedule later)
        self.jssp_data = None
        self.makespan: float = 0.0

        ACTIVE_MACHINE_DECISION = self

        # load immediately in __init__ (no layout needed — gantt is an already-complete file)
        if os.path.exists(self.planned_gantt_csv):
            self._load_gantt()
        else:
            print(f"[MachineDecisionMaker] planned_gantt.csv not found: "
                  f"{self.planned_gantt_csv} (retry in run_scheduling)")

    # ------------------------------------------------------------------
    def _load_gantt(self):
        self.schedule = GanttSchedule(
            gantt_csv=self.planned_gantt_csv,
            step_info_csv=self.step_info_path if os.path.exists(self.step_info_path) else None,
            pt_scale=self.pt_scale,
        )
        self.jssp_data = self.schedule  # backward-compat alias
        # planned makespan = max planned_end over all ops
        # + for strict plan-order execution: per-machine op sequence (in planned_start order)
        mk = 0.0
        seq = defaultdict(list)
        for r in self.schedule.routes.values():
            for op in r.ops:
                if op.planned_end > mk:
                    mk = op.planned_end
                seq[op.machine].append((op.planned_start, op.lot_id, int(op.step_no)))
        self.makespan = mk
        self._machine_seq = {m: sorted(v) for m, v in seq.items()}   # m_name -> [(start, lot, step)]
        self._machine_ptr = {m: 0 for m in self._machine_seq}        # index of next plan op to process

    # ------------------------------------------------------------------
    # Role 1: gantt load (not schedule generation). Signature preserved to keep the connection.
    # transport_func / transport_resolver are already reflected in the gantt, so ignored.
    # ------------------------------------------------------------------
    def run_scheduling(self,
                       transport_func: Optional[Callable[[int, int], float]] = None,
                       transport_resolver: Optional[Callable[..., Any]] = None):
        print("\n[MachineDecisionMaker] ── gantt load ──")
        if self.schedule is None:
            if not os.path.exists(self.planned_gantt_csv):
                print(f"  planned_gantt.csv not found: {self.planned_gantt_csv}")
                return
            self._load_gantt()
        n_lots = len(self.schedule.lot_ids())
        n_mach = len(self.schedule.machines())
        n_ops = sum(len(r.ops) for r in self.schedule.routes.values())
        print(f"  file   : {self.planned_gantt_csv}")
        print(f"  content: {n_lots} lots × {n_mach} machines, {n_ops} ops")
        print(f"  realized proc distribution: {'ON' if self.schedule.step_dist else 'OFF (=planned)'}")
        print(f"  planned makespan: {self.makespan:,.0f}s = {self.makespan/3600:.2f}hr")
        print("[MachineDecisionMaker] ── done ──\n")

    # ------------------------------------------------------------------
    # Role 2: plan-order dispatch — min planned_ready among in_buffer arrivals
    # ------------------------------------------------------------------
    def choose_next_job(self, machine_station):
        if not machine_station.in_buffer:
            return None

        # strict plan-order: the machine processes ops exactly in the planned order.
        # If the lot for the next planned op has not arrived yet, return None -> machine *waits* (idle).
        # (does not process another arrived lot first -> realized is a clean right-shift of the plan)
        strict = bool(getattr(self.jssp_cfg, "machine_strict_plan_order", True))
        m_name = getattr(machine_station, "machine_name", None)
        seq = getattr(self, "_machine_seq", {}).get(m_name) if (strict and m_name) else None
        if seq is not None:
            ptr = self._machine_ptr.get(m_name, 0)
            if ptr >= len(seq):
                return None
            _, plot, pstep = seq[ptr]
            for job in machine_station.in_buffer:
                if (getattr(job, "lot_id", "") == plot
                        and int(getattr(job, "step_no", -1)) == pstep):
                    self._machine_ptr[m_name] = ptr + 1
                    return job
            return None   # next planned lot has not arrived yet -> wait

        # work-conserving fallback (strict off / no seq): min planned_ready among arrivals
        sched = self.schedule

        def key(job):
            pr = None
            if sched is not None:
                pr = sched.planned_ready(getattr(job, "lot_id", ""),
                                         getattr(job, "step_no", 0))
            return (pr if pr is not None else float("inf"),
                    job.created_time, job.job_id)

        return min(machine_station.in_buffer, key=key)

    # ------------------------------------------------------------------
    # backward-compat: when some code asks for plan info (empty dict if absent)
    # ------------------------------------------------------------------
    def get_plan_info(self, lot_id: str, step_no: int) -> dict:
        if self.schedule is None:
            return {}
        op = self.schedule.op(lot_id, step_no)
        if op is None:
            return {}
        return {
            "planned_start": op.planned_start,
            "planned_end": op.planned_end,
            "machine": op.machine,
            "process_time": op.planned_proc,
        }


