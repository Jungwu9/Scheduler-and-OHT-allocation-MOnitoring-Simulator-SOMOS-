class GanttHTMLExporter:
    """Two-tier bar gantt showing processing and transport separately, for both planned and actual."""

    JOB_COLORS = [
        "#4E79A7", "#F28E2B", "#E15759", "#76B7B2", "#59A14F",
        "#EDC948", "#B07AA1", "#FF9DA7", "#9C755F", "#BAB0AC",
        "#3D405B", "#81B29A", "#F2CC8F", "#E07A5F", "#264653",
    ]
    TRANSPORT_COLOR = "#8b949e"

    def __init__(self, jssp_cfg: JSSPConfig):
        self.cfg = jssp_cfg
        self.window = int(jssp_cfg.window_sec)
        self.transport_len = 0.0

    def _fmt(self, sec):
        s = max(0, int(float(sec)))
        h, r = divmod(s, 3600)
        m, s = divmod(r, 60)
        return f"{h:02d}:{m:02d}:{s:02d}"

    def _pct(self, v):
        return f"{(float(v) / self.window * 100) if self.window else 0.0:.3f}%"

    def _read_csv(self, path):
        if not os.path.exists(path):
            return []
        with open(path, newline='', encoding='utf-8') as f:
            return list(csv.DictReader(f))

    def _bar_html(self, left, width, color, label, title, extra_class=""):
        if width <= 0:
            return ""
        cls = f"bar {extra_class}".strip()
        safe_label = label if width > 1.2 else ""
        return (
            f'<div class="{cls}" style="left:{left:.3f}%;width:{width:.3f}%;background:{color}" '
            f'title="{title}"><span class="bl">{safe_label}</span></div>\n'
        )

    @staticmethod
    def _digits(s):
        return ''.join(c for c in str(s) if c.isdigit())

    def _m_int(self, s):
        """'M7'/'7'/'M07' -> 7 (machine number). -1 on failure."""
        d = self._digits(s)
        return int(d) if d else -1

    def _lot_int(self, s):
        """'L0057' -> 57 (integer for color/identification). 0 on failure."""
        d = self._digits(s)
        return int(d) if d else 0

    def _build_planned_rows(self, planned_rows):
        """planned_gantt.csv -> planned rows per machine (only ops within window)."""
        rows_by_machine = defaultdict(list)
        job_comp = {}
        for r in planned_rows:
            try:
                machine_id = self._m_int(r.get('machine'))
                lot = r.get('lot_id', '')
                lot_i = self._lot_int(lot)
                step = int(float(r.get('step_no') or 0))
                st = float(r['start_sec'])
                et = float(r['end_sec'])
                proc = float(r.get('planned_proc_sec') or (et - st))
                ready = float(r.get('ready_at_machine_sec') or st)
                ptravel = float(r.get('planned_travel_sec') or 0.0)
            except Exception:
                continue
            if machine_id < 0:
                continue
            if self.window and st > self.window:   # skip plans outside window (limit to comparable range)
                continue
            trans_start = max(0.0, ready - ptravel)   # planned transport into this step (just before arrival)
            job_comp[lot_i] = max(job_comp.get(lot_i, 0.0), et)
            rows_by_machine[machine_id].append({
                'machine_id': machine_id, 'job_id': lot_i, 'lot_id': lot, 'op_index': step,
                'start': st, 'end': et, 'visual_end': et, 'proc': proc,
                'trans': ptravel, 'trans_start': trans_start,
            })
        return rows_by_machine, job_comp

    def _build_actual_rows(self, sim_rows, tmap):
        """log_machine_sim.csv (+ transport.csv join) -> actual rows per machine."""
        rows_by_machine = defaultdict(list)
        job_comp = {}
        for r in sim_rows:
            try:
                machine_id = self._m_int(r.get('machine_no') or r.get('machine_name'))
                lot = r.get('lot_id', '')
                lot_i = self._lot_int(lot)
                step = int(float(r.get('step_no') or 0))
                st = float(r['start_time'])
                et = float(r['end_time'])
                proc = max(0.0, float(r.get('process_time') or (et - st)))
                ready_dev = float(r.get('ready_deviation') or 0.0)
            except Exception:
                continue
            if machine_id < 0:
                continue
            # join actual transport into this step (transport.csv) -> transport bar just before arrival
            trans = 0.0
            trans_start = st
            tr = tmap.get((lot, step))
            if tr:
                try:
                    le = float(tr.get('load_end_time') or 0.0)
                    ue = float(tr.get('unload_end_time') or tr.get('dropoff_time') or 0.0)
                    if le > 0.0 and ue > le:
                        trans = ue - le
                        trans_start = le
                except Exception:
                    pass
            job_comp[lot_i] = max(job_comp.get(lot_i, 0.0), et)
            rows_by_machine[machine_id].append({
                'machine_id': machine_id, 'job_id': lot_i, 'lot_id': lot, 'op_index': step,
                'start': st, 'end': et, 'visual_end': et, 'proc': proc,
                'trans': trans, 'trans_start': trans_start, 'ready_dev': ready_dev,
            })
        return rows_by_machine, job_comp

    def _render_machine_rows(self, rows_by_machine, machine_ids, mode='planned'):
        """Machine row = processing (machine occupancy) only. Transport is a rail/OHT resource,
        so it is not drawn on the machine row. Gaps between bars = machine idle/starvation
        (transport delay / waiting). Planned is packed with no gaps; actual develops gaps
        equal to the transport delay, exposing starvation."""
        html_rows = ""
        max_end = 0.0
        scale = float(getattr(self, "_axis", 0.0) or self.window or 1.0)
        for machine_id in machine_ids:
            bars = ""
            entries = sorted(rows_by_machine.get(machine_id, []), key=lambda x: x['start'])
            for r in entries:
                max_end = max(max_end, r.get('visual_end', r.get('end', 0.0)))
                lot_i = r['job_id']
                col = self.JOB_COLORS[(lot_i - 1) % len(self.JOB_COLORS)] if lot_i > 0 else self.JOB_COLORS[0]
                proc_left = r['start'] / scale * 100
                proc_width = r['proc'] / scale * 100
                lab = r.get('lot_id', '')
                tag = 'Planned' if mode == 'planned' else 'Actual'
                proc_tip = (
                    f"[{tag}] {lab} / step {r['op_index']} → M{machine_id:02d}&#10;"
                    f"Start:{self._fmt(r['start'])}  End:{self._fmt(r['end'])}&#10;"
                    f"Proc:{r['proc']:.0f}s"
                )
                if mode == 'actual':
                    proc_tip += f"  ready_dev:{r.get('ready_dev', 0.0):+.0f}s"
                bars += self._bar_html(proc_left, proc_width, col, '', proc_tip, 'proc-bar')

            html_rows += (
                f'<div class="g-row"><div class="g-lbl">M{machine_id:02d}</div>'
                f'<div class="g-track">{bars}</div></div>\n'
            )
        return html_rows, max_end

