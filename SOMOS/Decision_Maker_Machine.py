        planned_path = getattr(self.cfg, "planned_gantt_csv", "")
        if not planned_path or not os.path.exists(planned_path):
            print(f"[GanttHTMLExporter] planned_gantt.csv not found -> skip: {planned_path}")
            return ""

        planned = self._read_csv(planned_path)
        sim_rows = self._read_csv(self.cfg.log_machine_csv.replace('.csv', '_sim.csv'))
        out_dir = os.path.dirname(os.path.abspath(self.cfg.log_oht_csv)) or '.'
        transport = self._read_csv(os.path.join(out_dir, 'transport.csv'))
        oht = self._read_csv(self.cfg.log_oht_csv)

        # index transport.csv by (lot_id, step_no) -> for joining actual arrival transport bars
        tmap = {}
        for tr in transport:
            try:
                tmap[(tr.get('lot_id', ''), int(float(tr.get('step_no') or -1)))] = tr
            except Exception:
                continue

        planned_by_m, planned_job_comp = self._build_planned_rows(planned)
        actual_by_m, actual_job_comp = self._build_actual_rows(sim_rows, tmap)

        machine_ids = sorted(set(planned_by_m.keys()) | set(actual_by_m.keys()))
        n_m = len(machine_ids)
        n_j = len({self._lot_int(r.get('lot_id', '')) for r in sim_rows}) if sim_rows else 0

        planned_makespan = max((r['visual_end'] for rows in planned_by_m.values() for r in rows), default=0.0)
        actual_makespan = max((r['visual_end'] for rows in actual_by_m.values() for r in rows), default=0.0)
        axis_makespan = max(planned_makespan, actual_makespan, float(self.window))
        self._axis = axis_makespan   # same scale for bars/ticks

